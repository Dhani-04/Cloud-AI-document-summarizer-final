"""
export_utils.py - Multi-format Document Export Engine
Generates downloadable outputs:
- Formatted PDF summary (via ReportLab)
- Markdown (.md)
- Plain Text (.txt)
- Exam Preparation Notes (.txt / .md)
- Important Questions & Answers (.json / .txt)
"""

import io
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

def summary_to_markdown(summary: Dict[str, Any], doc_title: str = "Document Summary") -> str:
    """Converts the 14-section JSON summary into clean, formatted Markdown."""
    md = []
    md.append(f"# Academic AI Summary: {doc_title}")
    md.append(f"*Generated by Cloud-Based AI Document Summarizer*\n")
    md.append("---\n")

    # 1. Executive Summary
    md.append("## 1. Executive Summary")
    md.append(summary.get("executive_summary", "N/A") + "\n")

    # 2. Document Introduction
    md.append("## 2. Document Introduction")
    md.append(summary.get("document_introduction", "N/A") + "\n")

    # 3. Section-wise Summary
    md.append("## 3. Section-wise Summary")
    for s in summary.get("section_wise_summary", []):
        md.append(f"- {s}")
    md.append("")

    # 4. Chapter-wise Explanation
    md.append("## 4. Chapter-wise Explanation")
    for c in summary.get("chapter_wise_explanation", []):
        md.append(f"- {c}")
    md.append("")

    # 5. Detailed Concept Explanations
    md.append("## 5. Detailed Concept Explanations")
    for d in summary.get("detailed_concept_explanations", []):
        md.append(f"- {d}")
    md.append("")

    # 6. Key Concepts
    md.append("## 6. Key Concepts")
    for kc in summary.get("key_concepts", []):
        md.append(f"- **{kc}**")
    md.append("")

    # 7. Important Definitions
    md.append("## 7. Important Definitions")
    for defn in summary.get("important_definitions", []):
        term = defn.get("term", "")
        definition = defn.get("definition", "")
        md.append(f"- **{term}**: {definition}")
    md.append("")

    # 8. Important Points
    md.append("## 8. Important Points")
    for pt in summary.get("important_points", []):
        md.append(f"* {pt}")
    md.append("")

    # 9. Keywords
    md.append("## 9. Keywords")
    keywords = summary.get("keywords", [])
    md.append(", ".join([f"`{k}`" for k in keywords]) + "\n")

    # 10. Examples and Applications
    md.append("## 10. Examples and Applications")
    for ex in summary.get("examples_and_applications", []):
        md.append(f"- {ex}")
    md.append("")

    # 11. Important Findings
    md.append("## 11. Important Findings")
    for f in summary.get("important_findings", []):
        md.append(f"- {f}")
    md.append("")

    # 12. Conclusion
    md.append("## 12. Conclusion")
    md.append(summary.get("conclusion", "N/A") + "\n")

    # 13. Exam Preparation Notes
    md.append("## 13. Exam Preparation Notes")
    for note in summary.get("exam_preparation_notes", []):
        md.append(f"> **Revision Note:** {note}")
    md.append("")

    # 14. Important Questions and Answers
    md.append("## 14. Important Questions and Answers")
    for qa in summary.get("important_questions_and_answers", []):
        q = qa.get("question", "")
        a = qa.get("answer", "")
        md.append(f"**Q: {q}**\n\n**A:** {a}\n")

    return "\n".join(md)

def summary_to_plain_text(summary: Dict[str, Any], doc_title: str = "Document Summary") -> str:
    """Converts the summary into clean plain text for easy reading or notes apps."""
    md_version = summary_to_markdown(summary, doc_title)
    # Strip basic markdown markers
    clean = md_version.replace("## ", "").replace("# ", "").replace("**", "").replace("`", "")
    return clean

def generate_pdf_summary_bytes(summary: Dict[str, Any], doc_title: str = "Document Summary") -> bytes:
    """Generates a professional academic PDF document using ReportLab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )
    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#1E3A8A'),
        spaceAfter=12
    )
    h2_style = ParagraphStyle(
        'SectionHeader',
        parent=styles['Heading2'],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#2563EB'),
        spaceBefore=12,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#1F2937'),
        spaceAfter=6
    )

    story = []
    story.append(Paragraph(f"AI Document Summary: {doc_title}", title_style))
    story.append(Paragraph("Cloud-Based AI Document Summarizer • Academic Edition", styles['Italic']))
    story.append(Spacer(1, 14))

    # Add 14 sections
    sections = [
        ("1. Executive Summary", summary.get("executive_summary", "")),
        ("2. Document Introduction", summary.get("document_introduction", "")),
        ("3. Conclusion", summary.get("conclusion", ""))
    ]

    for title, text in sections:
        if text:
            story.append(Paragraph(title, h2_style))
            story.append(Paragraph(str(text), body_style))
            story.append(Spacer(1, 6))

    # Key Concepts
    key_concepts = summary.get("key_concepts", [])
    if key_concepts:
        story.append(Paragraph("Key Concepts", h2_style))
        concepts_text = " • ".join([str(c) for c in key_concepts])
        story.append(Paragraph(concepts_text, body_style))
        story.append(Spacer(1, 6))

    # Exam Notes
    exam_notes = summary.get("exam_preparation_notes", [])
    if exam_notes:
        story.append(Paragraph("Exam Preparation Notes", h2_style))
        for n in exam_notes:
            story.append(Paragraph(f"• {n}", body_style))
        story.append(Spacer(1, 6))

    # Questions and Answers
    qas = summary.get("important_questions_and_answers", [])
    if qas:
        story.append(Paragraph("Important Questions & Answers", h2_style))
        for item in qas:
            q = item.get("question", "")
            a = item.get("answer", "")
            story.append(Paragraph(f"<b>Q: {q}</b>", body_style))
            story.append(Paragraph(f"A: {a}", body_style))
            story.append(Spacer(1, 4))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
